"""Snapshot project names/links from a reviewed official clients.md download.

Usage: python import-acp-clients.py /path/to/clients.md YYYY-MM-DD
No network access, descriptions copied, or agent execution.
"""

from datetime import date
import json
from pathlib import Path
import re
import sys

snapshot = date.fromisoformat(sys.argv[2])
rows, seen = [], set()
category, parent = "Clients", ""
for line in Path(sys.argv[1]).read_text().splitlines():
    if line.startswith("## "):
        category, parent = line[3:].strip(), ""
    if not line.lstrip().startswith("* "):
        continue
    indent = len(line) - len(line.lstrip())
    bullet = line.strip()[2:]
    match = re.search(r"\[([^\]]+)\]\((https://[^)]+)\)", bullet)
    if not match:
        if indent == 0:
            parent = bullet
        continue
    name, url = match[1].replace("`", "").replace("\\_", "_"), match[2]
    leading = bullet[: match.start()].strip()
    if leading:
        name = leading + " " + name
    if indent and parent:
        name = parent + " · " + name
    if indent == 0:
        parent = name
    if (name, url) not in seen:
        seen.add((name, url))
        rows.append((name, url, category))
lines = [
    "// Generated by scripts/import-acp-clients.py from the official ACP directory.",
    "// External projects, not connectable agent server profiles.",
    "struct ACPClientProject: Identifiable {",
    "  let name: String",
    "  let url: String",
    "  let category: String",
    "  var id: String { name + url }",
    "}",
    "",
    "enum ACPClientDirectory {",
    '  static let source = "https://agentclientprotocol.com/get-started/clients"',
    f'  static let snapshotDate = "{snapshot.strftime("%-d %b %Y")}"',
    "  static let projects: [ACPClientProject] = [",
]
for row in rows:
    name, url, category = [json.dumps(value, ensure_ascii=False) for value in row]
    lines.append(f"    ACPClientProject(name: {name}, url: {url}, category: {category}),")
lines += ["  ]", "}", ""]
destination = Path(__file__).resolve().parents[1] / "Sources/SuperQode/ACPClientDirectory.swift"
destination.write_text("\n".join(lines))
print(f"Imported {len(rows)} directory entries")
