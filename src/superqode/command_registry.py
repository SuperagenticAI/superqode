def command_metadata():
    """Canonical colon-command descriptions for help and palette generation."""
    metadata = {}
    for command in DEFAULT_COMMANDS:
        canonical = ":" + command.command.lstrip(":/")
        metadata.setdefault(canonical, command)
    return metadata


